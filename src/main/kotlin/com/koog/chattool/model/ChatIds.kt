package com.koog.chattool.model

/**
 * Правила для идентификаторов диалогов.
 *
 * id диалога определяет имя файла на диске, поэтому он строго ограничен паттерном:
 * это защита от path traversal — символы '/', '\\', '..' и т.п. недопустимы.
 * Невалидный id отклоняется валидатором (routes), а хранилище проверяет его
 * повторно (defense in depth).
 */
object ChatIds {
    /** Допустимый id: буква или цифра в начале, далее буквы/цифры/'.'/'_'/'-'; длина 1..64. */
    val PATTERN: Regex = Regex("^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")

    /** Проверка id на соответствие паттерну. */
    fun isValid(id: String): Boolean = PATTERN.matches(id)
}
